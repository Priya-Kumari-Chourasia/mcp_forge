"""
TRY IT - chat with a generated MCP server, the way Claude Desktop does.

The web UI's "Try it" tab (and the command line, see the bottom of this file)
lets anyone check a generated server with real questions, without installing
anything:

    1. start the server.py as its own process and connect an MCP client over
       stdio - the same transport Claude Desktop uses
    2. read the server's tool list and hand those tools to an LLM (Groq)
    3. the agent loop: the LLM either answers, or asks for tool calls; each
       call goes to the server over MCP, and the result goes back to the LLM,
       until it answers (or MAX_STEPS calls have been made)

Safe by default:
    - Only READ-ONLY tools are offered unless "allow changes" is on, so a
      question cannot delete data on a shared API by accident. (Claude Desktop
      asks before running a destructive tool; this panel simply leaves them out.)
    - The server process gets a minimal environment: no Groq key, only the
      variables this API needs (its base URL and credentials, if set) and
      proxy settings.

Usage:  python try_it.py generated/<api-name>/server.py "Find available pets"
"""

import asyncio
import json
import os
import sys

from langchain_core.messages import HumanMessage, SystemMessage, ToolMessage

MAX_STEPS = 6                 # tool calls per question, so a confused model cannot loop forever
MAX_RESULT_CHARS = 6000       # a tool result longer than this is cut before it goes back to the LLM
PASSED_THROUGH = ("HTTPS_PROXY", "HTTP_PROXY", "NO_PROXY", "https_proxy", "http_proxy", "no_proxy",
                  "SSL_CERT_FILE", "REQUESTS_CA_BUNDLE")


def system_message(api_name: str) -> SystemMessage:
    return SystemMessage(content=(
        f"You are testing an MCP server for {api_name}, generated by MCP-Forge. Answer the user's "
        f"questions by calling its tools; do not invent data the tools did not return. If a tool "
        f"returns an error, say what the error was. Keep answers short."))


def server_environment(env_names) -> dict:
    """What the server process may see, on top of the SDK's minimal defaults."""
    return {name: os.environ[name] for name in [*env_names, *PASSED_THROUGH] if os.environ.get(name)}


def is_read_only(tool) -> bool:
    return bool(tool.annotations and tool.annotations.read_only_hint)


def tool_spec(tool) -> dict:
    """An MCP tool in the function-calling format LLM APIs (Groq, OpenAI) accept."""
    return {"type": "function", "function": {
        "name": tool.name,
        "description": tool.description or tool.name,
        "parameters": tool.input_schema or {"type": "object", "properties": {}},
    }}


def result_text(result) -> str:
    """The text an LLM should see for one tool result: the structured data when
    there is some, otherwise the text parts (an error message, for instance)."""
    if result.structured_content is not None and not result.is_error:
        text = json.dumps(result.structured_content.get("result", result.structured_content), ensure_ascii=False)
    else:
        text = "\n".join(getattr(part, "text", "") for part in result.content)
    if len(text) > MAX_RESULT_CHARS:
        text = text[:MAX_RESULT_CHARS] + f"... [cut: {len(text)} characters in total]"
    return ("ERROR: " + text) if result.is_error else text


async def _ask(server_path, messages, model, allow_changes, env_names):
    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client

    params = StdioServerParameters(command=sys.executable, args=[os.path.abspath(server_path)],
                                   env=server_environment(env_names))
    trace = []
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            tools = (await session.list_tools()).tools
            offered = [t for t in tools if allow_changes or is_read_only(t)]
            names = {t.name for t in offered}
            bound = model.bind_tools([tool_spec(t) for t in offered])

            for _ in range(MAX_STEPS):
                reply = await bound.ainvoke(messages)
                messages.append(reply)
                if not reply.tool_calls:
                    return reply.content, trace, len(tools) - len(offered)
                for call in reply.tool_calls:
                    if call["name"] in names:
                        result = await session.call_tool(call["name"], call.get("args") or {})
                        text = result_text(result)
                    else:
                        text = (f"ERROR: the tool '{call['name']}' is not available here "
                                f"(tools that change data are turned off).")
                    trace.append({"tool": call["name"], "args": call.get("args") or {},
                                  "error": text.startswith("ERROR:"), "result": text[:300]})
                    messages.append(ToolMessage(content=text, tool_call_id=call["id"]))
            return (f"Stopped after {MAX_STEPS} rounds of tool calls without a final answer."), trace, \
                len(tools) - len(offered)


def describe_error(error: BaseException) -> str:
    """The real reason a chat failed. The MCP client runs inside task groups, so an
    error arrives wrapped in "unhandled errors in a TaskGroup"; unwrap it."""
    while getattr(error, "exceptions", None):
        error = error.exceptions[0]
    return f"{type(error).__name__}: {error}"


def ask(server_path: str, messages: list, question: str, model, allow_changes: bool = False,
        env_names=(), timeout: float = 120) -> dict:
    """Answers one question. `messages` is the conversation so far (start it with
    system_message()); it is extended in place, so follow-up questions have context.
    Returns {"answer", "trace": [one entry per tool call], "hidden_tools": n}."""
    messages.append(HumanMessage(content=question))
    answer, trace, hidden = asyncio.run(asyncio.wait_for(
        _ask(server_path, messages, model, allow_changes, list(env_names)), timeout))
    return {"answer": answer, "trace": trace, "hidden_tools": hidden}


if __name__ == "__main__":
    import llm
    if len(sys.argv) < 3:
        sys.exit('Usage: python try_it.py <path to server.py> "your question" [--allow-changes]')
    model = llm.chat_model()
    if model is None:
        sys.exit("Try it needs a real LLM: set GROQ_API_KEY in .env")
    conversation = [system_message(os.path.basename(os.path.dirname(os.path.abspath(sys.argv[1]))))]
    outcome = ask(sys.argv[1], conversation, sys.argv[2], model, allow_changes="--allow-changes" in sys.argv)
    for step in outcome["trace"]:
        print(f"  tool: {step['tool']}({json.dumps(step['args'])}) -> {step['result'][:120]}")
    print(outcome["answer"])
