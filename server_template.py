_REQUEST_HELPER = '''

def _request(method, path, *, params=None, json=None, data=None, headers=None):
    """Sends one request to the API. Every tool below calls this.

    - prefixes BASE_URL and adds the credentials configured in AUTH
    - leaves out query parameters whose value is None (not set by the AI)
    - raises ToolError for an HTTP error, naming the status code: MCP clients
      show a ToolError's message to the AI, while any other exception reaches
      it only as a generic "Error executing tool"
    """
    if not BASE_URL:
        raise ToolError(f"The API base URL is not set. Set the {BASE_URL_ENV} environment variable.")
    params = {key: value for key, value in (params or {}).items() if value is not None}
    headers = dict(headers or {})
    cookies = {}
    for entry in AUTH:
        if entry["type"] == "basic":
            username, password = os.environ.get(entry["env"]), os.environ.get(entry["env_password"])
            if username and password:
                token = base64.b64encode(f"{username}:{password}".encode()).decode()
                headers["Authorization"] = f"Basic {token}"
            continue
        value = os.environ.get(entry["env"])
        if not value:
            continue                              # not configured: send the request without it
        if entry["type"] == "bearer":
            headers["Authorization"] = f"Bearer {value}"
        elif entry["type"] == "header":
            headers[entry["name"]] = value
        elif entry["type"] == "query":
            params[entry["name"]] = value
        elif entry["type"] == "cookie":
            cookies[entry["name"]] = value

    try:
        response = httpx.request(method, BASE_URL + path, params=params, json=json, data=data,
                                 headers=headers, cookies=cookies, timeout=30, follow_redirects=True)
    except httpx.HTTPError as error:
        raise ToolError(f"{method} {path} could not reach the API: {error}") from error

    if response.is_error:
        raise ToolError(f"{method} {path} failed with HTTP {response.status_code}: {response.text[:1000]}")
    if not response.content:
        return {"status": response.status_code}
    if "json" in response.headers.get("content-type", ""):
        return response.json()
    return response.text
'''


def render_header(meta: dict) -> str:
    """The code above the tools: imports, the server object, BASE_URL, AUTH and
    _request(). The validator runs the tools with this exact header, so what was
    validated is what gets packaged."""
    prefix = env_prefix(meta)
    base_env = f"{prefix}_BASE_URL"
    default_base = (meta.get("base_url") or "").rstrip("/")
    auth = auth_config(meta)

    settings = [f"  {base_env:<24} the API's base URL (default: {default_base or 'none - required'})"]
    for entry in auth:
        kind = {"bearer": "access token", "basic": "username", "header": "API key",
                "query": "API key", "cookie": "API key"}[entry["type"]]
        settings.append(f"  {entry['env']:<24} {kind}")
        if entry.get("env_password"):
            settings.append(f"  {entry['env_password']:<24} password")

    if default_base:
        base_line = f"BASE_URL = (os.environ.get({base_env!r}) or {default_base!r}).rstrip(\"/\")"
    else:
        # No base URL in the docs. API_BASE_URL is the variable MCP-Forge's validator sets.
        base_line = (f"BASE_URL = (os.environ.get({base_env!r}) or os.environ.get(\"API_BASE_URL\") "
                     f"or \"\").rstrip(\"/\")")

    title = display_name(meta).replace('"""', "'''").replace("\\", "/")     # safe inside a docstring
    return (
        f'"""\nMCP server for {title}.\n'
        f"Generated by MCP-Forge. Every tool was validated before packaging.\n\n"
        f"Settings (environment variables):\n" + "\n".join(settings) + '\n"""\n'
        "import base64\n"
        "import os\n"
        "from typing import Annotated, Any, Literal, Optional, Union\n\n"
        "import httpx\n"
        "from pydantic import Field\n"
        "from mcp.server.mcpserver import MCPServer\n"
        "from mcp.server.mcpserver.exceptions import ToolError\n"
        "from mcp.types import ToolAnnotations\n\n"
        f"server = MCPServer({display_name(meta)!r})\n\n"
        f"BASE_URL_ENV = {base_env!r}\n"
        f"{base_line}\n\n"
        "# How this API accepts credentials. Each value is read from an environment\n"
        "# variable, so secrets never pass through the AI client as tool arguments.\n"
        f"AUTH = {auth!r}\n"
        + _REQUEST_HELPER
    )


