def tool_names_in(code: str) -> list:
    """Public top-level functions = the tools. Names starting with _ are helpers."""
    tree = ast.parse(code)
    return [n.name for n in tree.body
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")]


_ANNOTATIONS_BY_METHOD = {
    # read_only: never changes anything. destructive: may change or delete existing data.
    # idempotent: calling twice has the same effect as calling once.
    "GET": "read_only_hint=True, idempotent_hint=True",
    "POST": "read_only_hint=False, destructive_hint=False, idempotent_hint=False",
    "PUT": "read_only_hint=False, destructive_hint=True, idempotent_hint=True",
    "PATCH": "read_only_hint=False, destructive_hint=True, idempotent_hint=False",
    "DELETE": "read_only_hint=False, destructive_hint=True, idempotent_hint=True",
}


def _decorator(method: str) -> str:
    hints = _ANNOTATIONS_BY_METHOD.get((method or "").upper())
    if not hints:
        return "@server.tool()"
    return f"@server.tool(annotations=ToolAnnotations({hints}, open_world_hint=True))"


def package_server(tool_code: str, endpoints: list, meta: dict):
    """Header + the validated tools, each under a @server.tool(...) decorator
    (placed with ast, not string guessing), + a __main__ block that starts the
    server. Returns (server_code, [{"name", "description"}, ...])."""
    tree = ast.parse(tool_code)
    lines = tool_code.split("\n")
    method_by_name = {ep.get("name"): ep["method"] for ep in endpoints}
    functions = [n for n in tree.body
                 if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")]
    tool_info = [{"name": n.name, "description": ast.get_docstring(n) or "No description"} for n in functions]

    # Insert decorators bottom-to-top so earlier line numbers don't shift.
    for node in sorted(functions, key=lambda n: n.lineno, reverse=True):
        lines.insert(node.lineno - 1, _decorator(method_by_name.get(node.name)))

    code = render_header(meta) + "\n\n" + "\n".join(lines).strip() + '\n\n\nif __name__ == "__main__":\n    server.run()\n'
    return code, tool_info


def claude_desktop_config(meta: dict, server_path: str) -> dict:
    """The entry to paste into Claude Desktop's config. The command is the Python
    that ran MCP-Forge, which has every package the server needs. Credentials go
    in "env": an empty value means "not set", so nothing is sent until you fill it."""
    entry = {"command": sys.executable, "args": [os.path.abspath(server_path)]}
    env_names = auth_env_names(meta)
    if env_names:
        entry["env"] = {name: "" for name in env_names}
    return {"mcpServers": {folder_name(meta): entry}}


def readme(meta: dict, tool_info: list, server_path: str) -> str:
    prefix = env_prefix(meta)
    text = f"# {display_name(meta)} - MCP server\n\nGenerated by MCP-Forge. {len(tool_info)} tool(s):\n\n"
    for tool in tool_info:
        text += f"- **{tool['name']}**: {tool['description']}\n"
    text += "\n## Settings\n\n"
    text += f"- `{prefix}_BASE_URL`: the API's base URL (default: `{meta.get('base_url') or 'none, required'}`)\n"
    for name in auth_env_names(meta):
        text += f"- `{name}`: credential, read from the environment and never shown to the AI\n"
    text += ("\n## Add to Claude Desktop\n\nPaste this into `claude_desktop_config.json` (Claude Desktop: "
             "Settings > Developer > Edit Config), fill in any credentials, then fully quit and reopen Claude:\n\n"
             "```json\n" + json.dumps(claude_desktop_config(meta, server_path), indent=2) + "\n```\n")
    text += "\n## Run it directly\n\n```\npip install -r requirements.txt\npython server.py\n```\n"
    return text


# ----------------------------------------------------------------------
# Final check: connect to the packaged server the way Claude Desktop does
# ----------------------------------------------------------------------

async def _list_tools_over_stdio(server_path: str) -> list:
    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client

    params = StdioServerParameters(command=sys.executable, args=[os.path.abspath(server_path)])
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            return [tool.name for tool in (await session.list_tools()).tools]


def check_with_mcp_client(server_path: str, expected_tools: list, timeout: float = 60) -> dict:
    """Starts the packaged server.py as a separate process, connects an MCP client
    over stdio (the transport Claude Desktop uses), initializes the session and
    lists the tools. This tests the actual file a user will run, not a copy of
    its functions. It runs the server's top-level code, as any MCP client would;
    the tools themselves were already exercised by the validator."""
    try:
        names = asyncio.run(asyncio.wait_for(_list_tools_over_stdio(server_path), timeout))
    except Exception as error:
        detail = str(error) or type(error).__name__
        if hasattr(error, "exceptions"):                       # an ExceptionGroup from the client
            detail = "; ".join(f"{type(e).__name__}: {e}" for e in error.exceptions)
        return {"passed": False, "tools_listed": 0, "missing": sorted(expected_tools),
                "error": f"{type(error).__name__}: {detail}"[:500]}
    missing = sorted(set(expected_tools) - set(names))
    return {"passed": not missing, "tools_listed": len(names), "missing": missing, "error": None}
