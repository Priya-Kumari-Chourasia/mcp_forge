"""
SERVER TEMPLATE - the fixed, hand-written part of every generated MCP server.

The LLM writes only the tool functions: one per endpoint, each a few lines
that call _request(). Everything that must be right every single time lives
here, written once and tested, instead of being re-generated (and possibly
gotten wrong) by the LLM in every tool:

  _request()     adds the base URL and the credentials, leaves out unset
                 parameters, and turns an HTTP error into a message that names
                 the status code, so the AI client can see what went wrong
  AUTH           credentials come from environment variables, never from
                 tool arguments, so a secret never passes through the AI
  annotations    each tool is marked read-only or destructive from its HTTP
                 method, so clients such as Claude can ask before deleting

This module also packages the finished server (server.py, README, a ready
Claude Desktop config) and checks it with a real MCP client.
"""

import asyncio
import ast
import json
import keyword
import os
import re
import sys
from urllib.parse import urlparse

# Versions the generated server is known to work with (the same ones MCP-Forge uses).
SERVER_REQUIREMENTS = "mcp==2.3.0\nhttpx==0.28.1\n"

# Names the header defines. A tool with one of these names would overwrite it.
RESERVED_NAMES = {"server", "httpx", "os", "base64", "Field", "ToolError", "ToolAnnotations",
                  "Annotated", "Any", "Literal", "Optional", "Union", "AUTH", "BASE_URL"}

# Words that say nothing about WHICH API this is, skipped when naming env variables.
_GENERIC_WORDS = {"swagger", "openapi", "api", "apis", "rest", "the", "service", "server",
                  "http", "https", "www", "json", "spec", "specification", "and", "of", "for"}


# ----------------------------------------------------------------------
# Names
# ----------------------------------------------------------------------

def python_name(text: str) -> str:
    """'findPetsByStatus' or 'issues/list-for-repo' -> a snake_case Python identifier."""
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text or "")       # camelCase -> camel_Case
    text = re.sub(r"[^0-9a-zA-Z]+", "_", text).strip("_").lower()
    if not text:
        text = "tool"
    if text[0].isdigit():
        text = "t_" + text
    if keyword.iskeyword(text):
        text += "_"
    return text


def assign_tool_names(endpoints: list) -> None:
    """Gives every endpoint a unique tool name, decided in code rather than by the
    LLM: the spec's operationId when it has one, otherwise method + path
    (GET /pet/{petId} -> get_pet_pet_id). Two batches generated by separate LLM
    calls can then never pick the same name."""
    used = set()
    for endpoint in endpoints:
        base = endpoint.get("operation_id") or f"{endpoint['method']} {endpoint['path']}"
        name = python_name(base)
        if name in RESERVED_NAMES:
            name += "_tool"
        candidate, n = name, 2
        while candidate in used:
            candidate, n = f"{name}_{n}", n + 1
        used.add(candidate)
        endpoint["name"] = candidate


def display_name(meta: dict) -> str:
    """'Swagger Petstore - OpenAPI 3.0', or the API's host when the docs give no title."""
    if meta.get("title"):
        return meta["title"]
    return urlparse(meta.get("base_url") or "").netloc or "Generated API"


def folder_name(meta: dict) -> str:
    """Folder for the output: from the title, or from the base URL when there is none."""
    source = meta.get("title") or meta.get("base_url") or "generated-api"
    return re.sub(r"[^a-zA-Z0-9]+", "-", source).strip("-").lower() or "generated-api"


def env_prefix(meta: dict) -> str:
    """Short upper-case prefix for this API's environment variables:
    'Swagger Petstore - OpenAPI 3.0' -> PETSTORE, 'GitHub v3 REST API' -> GITHUB,
    and with no title, https://api.bookstore.example/v2 -> BOOKSTORE."""
    if meta.get("title"):
        words = re.findall(r"[a-z0-9]+", meta["title"].lower())
    else:
        words = urlparse(meta.get("base_url") or "").netloc.split(".")[:-1]     # drop the TLD
    words = [w for w in words if w not in _GENERIC_WORDS and not re.fullmatch(r"v?\d+", w)]
    return "_".join(words[:2]).upper() or "API"


# ----------------------------------------------------------------------
# Authentication
# ----------------------------------------------------------------------

def auth_config(meta: dict) -> list:
    """The AUTH list written into the server: each credential the API accepts,
    with the environment variable it is read from.
        API key   -> <PREFIX>_API_KEY
        token     -> <PREFIX>_TOKEN             (Bearer and OAuth2)
        basic     -> <PREFIX>_USERNAME and <PREFIX>_PASSWORD
    A second scheme of the same kind gets its own scheme name appended."""
    prefix = env_prefix(meta)
    config, used = [], set()

    def unique(env, scheme):
        if env in used:
            env = f"{env}_{python_name(scheme).upper()}"
        used.add(env)
        return env

    for scheme in meta.get("auth") or []:
        kind = scheme["type"]
        if kind in ("header", "query", "cookie"):
            config.append({"type": kind, "name": scheme["name"],
                           "env": unique(f"{prefix}_API_KEY", scheme.get("scheme", kind))})
        elif kind == "bearer":
            config.append({"type": "bearer", "env": unique(f"{prefix}_TOKEN", scheme.get("scheme", kind))})
        elif kind == "basic":
            config.append({"type": "basic", "env": unique(f"{prefix}_USERNAME", scheme.get("scheme", kind)),
                           "env_password": unique(f"{prefix}_PASSWORD", scheme.get("scheme", kind))})
    return config


def auth_env_names(meta: dict) -> list:
    names = []
    for entry in auth_config(meta):
        names.append(entry["env"])
        if entry.get("env_password"):
            names.append(entry["env_password"])
    return names


def parse_auth_option(option: str) -> dict:
    """The --auth command-line option, for APIs whose spec (or prose docs) does not
    declare how to authenticate:  bearer | basic | header:NAME | query:NAME"""
    option = option.strip()
    if option.lower() in ("bearer", "basic"):
        return {"scheme": option.lower(), "type": option.lower()}
    kind, _, name = option.partition(":")
    if kind.lower() in ("header", "query", "cookie") and name.strip():
        return {"scheme": f"{kind.lower()}_{name.strip()}", "type": kind.lower(), "name": name.strip()}
    raise ValueError(f"Unknown --auth value '{option}'. Use bearer, basic, header:NAME or query:NAME.")


